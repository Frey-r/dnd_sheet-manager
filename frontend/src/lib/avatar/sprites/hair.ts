const styleOf = (c: DrawCtx) => (c.a.hair > 0 ? STYLES[c.a.hair] ?? null : null);

/** Ties are ribbons in the outfit's second colour: trims, not hair. */
const TIE_TAGS: Record<string, string> = { q: 'trim', Q: 'trim' };

function hairKeys(c: DrawCtx) {
  const q = c.cloth[1];
  return keys(c.hair, { q: q.light, Q: q.shadow });
}

/** Layer behind the body (long hair, tails). */
export function drawHairBack(c: DrawCtx) {
  const s = styleOf(c);
  if (!s?.back) return;
  c.p.tag = 'hair-back';
  c.p.stamp(c.f.hx + OX, c.f.hy + OY, s.back, hairKeys(c), false, TIE_TAGS);
  c.p.tag = null;
}

/** Crown, bangs and side locks, over the face. */
export function drawHairFront(c: DrawCtx) {
  const { p, f, a, v, skin, hair } = c;
  const s = styleOf(c);
  if (!s) {
    // Bald: a little shine on the lit side of the scalp.
    if (a.hair === 0 && v.head === 'human') {
      p.tag = 'scalp';
      p.dots([[f.hx + 4, f.hy + 1], [f.hx + 3, f.hy + 2], [f.hx + 5, f.hy + 1]], skin.hi);
      p.tag = null;
    }
    return;
  }
  if (a.hair === 4) {
    // Mohawk: stubble on the shaved sides of the skull.
    const stubble = mix(skin.base, hair.base, 0.3);
    p.tag = 'scalp';
    for (let y = f.hy; y <= f.hy + 9; y++) {
      for (let x = f.hx; x <= f.hx + 14; x++) if (p.tagAt(x, y) === 'scalp') p.set(x, y, stubble);
    }
  }
  p.tag = 'hair';
  p.stamp(f.hx + OX, f.hy + OY, s.front, hairKeys(c), false, TIE_TAGS);
  p.tag = null;
}
